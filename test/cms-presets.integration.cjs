// Run only against a disposable local database after applying migrations.
const assert = require('node:assert/strict')
const { randomUUID } = require('node:crypto')
const { PrismaService } = require('../dist/prisma/prisma.service')
const { PagesService } = require('../dist/pages/pages.service')
const { PresetsService } = require('../dist/presets/presets.service')

async function main() {
  const url = new URL(process.env.DATABASE_URL || '')
  assert.ok(['127.0.0.1', 'localhost'].includes(url.hostname) && url.pathname.includes('test'), 'Use a disposable local test database')
  const db = new PrismaService()
  const pages = new PagesService(db)
  const presets = new PresetsService(db)
  const pageIds = [], presetIds = []
  try {
    const scope = `design|test|${randomUUID()}`
    const contentA = { title: { vi: 'Ký ức', en: 'Memory', ru: 'Память', zh: '记忆' }, background: '/uploads/anh.jpg', titleStyle: { fontFamily: 'serif', fontSize: 58, color: '#123456' }, items: [{ text: { vi: 'Một', en: 'One' }, image: '/uploads/item.jpg' }] }
    const blockPreset = await presets.create({ kind: 'block', scope, name: 'Bản một', payload: { block_type: 'design', content: contentA } })
    const blockPreset2 = await presets.create({ kind: 'block', scope, name: 'Bản hai', payload: { block_type: 'design', content: { ...contentA, titleStyle: { fontSize: 70 } } } })
    presetIds.push(blockPreset.id, blockPreset2.id)
    await presets.activate(blockPreset.id, 'scope')
    let blockList = await presets.list('block', scope)
    assert.equal(blockList.length, 2)
    assert.deepEqual(blockList.find(item => item.active).payload.content, contentA)
    await presets.activate(blockPreset2.id, 'scope')
    blockList = await presets.list('block', scope)
    assert.equal(blockList.filter(item => item.active).length, 1)
    assert.equal(blockList.find(item => item.active).id, blockPreset2.id)
    assert.deepEqual(await presets.list('block', 'design|other'), [])
    await presets.resetSelection({ kind: 'block', scope })
    assert.ok((await presets.list('block', scope)).every(item => !item.active))

    const source = await pages.createPage({ slug: `preset-source-${randomUUID()}`, title: { vi: 'Bản A', en: 'Version A' }, description: { vi: 'Mô tả' }, sub_nav: [{ anchor: 'gioi-thieu' }], is_published: false })
    pageIds.push(source.id)
    const block = await pages.createBlock({ page_id: source.id, block_type: 'design', content: contentA, is_visible: true, sort_order: 10, label: 'Ảnh chính' })
    const first = await presets.create({ kind: 'page', scope: source.id, source_page_id: source.id, name: 'Trang A' })
    presetIds.push(first.id)
    await pages.updatePage(source.id, { title: { vi: 'Bản B', en: 'Version B' } })
    await pages.updateBlock(block.id, { content: { ...contentA, title: { vi: 'Đã đổi', en: 'Changed' } } })
    const extra = await pages.createBlock({ page_id: source.id, block_type: 'quote_break', content: { quote: { vi: 'Giữ lại' } }, is_visible: false, sort_order: 20, label: 'Khối ẩn' })
    const second = await presets.create({ kind: 'page', scope: source.id, source_page_id: source.id, name: 'Trang B' })
    presetIds.push(second.id)
    await presets.activate(first.id, 'both')
    const before = await pages.getAdminPageBySlug(source.slug)
    await db.siteSetting.upsert({ where: { key: 'header_settings' }, create: { key: 'header_settings', value: { blockId: extra.id } }, update: { value: { blockId: extra.id } } })
    await assert.rejects(() => presets.applyPage(source.id, first.id), /header hoặc footer/)
    assert.equal((await presets.pageState(source.id)).can_reset, false)
    await db.siteSetting.delete({ where: { key: 'header_settings' } })
    await presets.applyPage(source.id, first.id)
    let loaded = await pages.getAdminPageBySlug(source.slug)
    assert.equal(loaded.page.title.vi, 'Bản A')
    assert.equal(loaded.blocks.length, 1)
    assert.equal(loaded.blocks[0].id, block.id)
    assert.deepEqual(loaded.blocks[0].content, contentA)
    assert.equal((await presets.pageState(source.id)).can_reset, true)
    await presets.applyPage(source.id, second.id)
    await presets.resetPage(source.id)
    const restored = await pages.getAdminPageBySlug(source.slug)
    assert.deepEqual(restored.page.title, before.page.title)
    assert.deepEqual(restored.blocks.map(({ id, content, is_visible, label }) => ({ id, content, is_visible, label })), before.blocks.map(({ id, content, is_visible, label }) => ({ id, content, is_visible, label })))
    assert.ok((await presets.list('page', source.id)).every(item => !item.active && !item.default_for_new_pages))
    assert.equal((await presets.pageState(source.id)).can_reset, false)

    const template = await pages.createPageTemplate({ name: 'Mẫu thử', source_page_id: source.id })
    pageIds.push(template.id)
    const savedTemplate = await presets.create({ kind: 'page', scope: template.id, source_page_id: template.id, name: 'Preset mẫu' })
    presetIds.push(savedTemplate.id)
    await presets.activate(savedTemplate.id, 'both')
    const templateBefore = await pages.getAdminPageBySlug(template.slug)
    await pages.updateBlock(templateBefore.blocks[0].id, { content: { title: { vi: 'Gốc mới' } } })
    const created = await presets.createPage(savedTemplate.id, { slug: `preset-copy-${randomUUID()}`, title: { vi: 'Trang nháp', en: 'Draft' }, source_template_id: template.id })
    pageIds.push(created.id)
    const copy = await pages.getAdminPageBySlug(created.slug)
    assert.equal(copy.page.is_published, false)
    assert.equal(copy.page.title.vi, 'Trang nháp')
    assert.deepEqual(copy.blocks[0].content, templateBefore.blocks[0].content)
    assert.notEqual(copy.blocks[0].id, templateBefore.blocks[0].id)
    const copyPreset = await presets.create({ kind: 'page', scope: copy.page.id, source_page_id: copy.page.id, name: 'Preset trang sao' })
    presetIds.push(copyPreset.id)
    await presets.activate(copyPreset.id, 'both')
    await presets.resetPage(created.id)
    const copyReset = await pages.getAdminPageBySlug(created.slug)
    assert.equal(copyReset.blocks[0].content.title.vi, 'Gốc mới')
    assert.equal(copyReset.page.title.vi, 'Trang nháp')
    assert.equal((await pages.getAdminPageBySlug(template.slug)).blocks[0].content.title.vi, 'Gốc mới')
    assert.ok((await presets.list('page', template.id)).every(item => !item.active && !item.default_for_new_pages))
    assert.ok((await presets.list('page', created.id)).every(item => !item.active && !item.default_for_new_pages))
    console.log('CMS preset integration checks passed')
  } finally {
    await db.cmsPreset.deleteMany({ where: { id: { in: presetIds } } })
    await db.page.deleteMany({ where: { id: { in: pageIds } } })
    await db.$disconnect()
  }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
