// Run only against a disposable local PostgreSQL database after migrations.
const assert = require('node:assert/strict')
const { randomUUID } = require('node:crypto')
const { PrismaService } = require('../dist/prisma/prisma.service')
const { PagesService } = require('../dist/pages/pages.service')

async function main() {
  const url = new URL(process.env.DATABASE_URL || '')
  assert.ok(['127.0.0.1', 'localhost'].includes(url.hostname) && url.pathname.includes('test'), 'Use a local test database')
  const db = new PrismaService()
  const pages = new PagesService(db)
  const ids = [], collectionIds = []
  try {
    const source = await pages.createPage({ slug: `nguon-${randomUUID()}`, title: { vi: 'Trang gốc', en: 'Original' }, sub_nav: [{ anchor: 'gioi-thieu', label: { vi: 'Giới thiệu' } }], is_published: false })
    ids.push(source.id)
    const collection = await pages.createPageTemplateCollection({ name: `Bộ sưu tập ${randomUUID()}` })
    const otherCollection = await pages.createPageTemplateCollection({ name: `Bộ sưu tập khác ${randomUUID()}` })
    collectionIds.push(collection.id, otherCollection.id)
    const block = await pages.createBlock({ page_id: source.id, block_type: 'card_grid', content: { title: { vi: 'Di sản', en: 'Heritage' }, cornerRadius: 7, cards: [{ image: '/heritage.jpg', href: '/vi/home' }] }, is_visible: true, label: 'Thẻ mẫu' })
    const template = await pages.createPageTemplate({ name: 'Mẫu di sản', source_page_id: source.id, collection_id: collection.id })
    ids.push(template.id)
    assert.equal(template.is_template, true)
    assert.equal(template.is_published, false)
    assert.equal(template.template_collection_id, collection.id)
    assert.equal((await pages.getPageTemplateCollections()).find(row => row.id === collection.id).template_count, 1)
    const stored = await pages.getAdminPageBySlug(template.slug)
    assert.deepEqual(stored.page.sub_nav, source.sub_nav)
    assert.deepEqual(stored.blocks[0].content, block.content)
    assert.equal(stored.blocks[0].label, 'Thẻ mẫu')
    assert.ok(!(await pages.getAdminPages()).some(row => row.id === template.id))
    assert.equal(await pages.getPublishedPageStatus(template.slug), null)
    await assert.rejects(() => pages.updatePage(template.id, { is_published: true }))
    await pages.updateBlock(block.id, { content: { title: { vi: 'Đã sửa trang gốc' } } })
    assert.deepEqual((await pages.getAdminPageBySlug(template.slug)).blocks[0].content, block.content)
    const clone = await pages.clonePageTemplate(template.id, 'Bản sao mẫu')
    ids.push(clone.id)
    assert.equal(clone.template_collection_id, collection.id)
    await pages.updatePageTemplate(clone.id, { collection_id: otherCollection.id })
    assert.equal((await pages.getPageTemplates()).find(row => row.id === clone.id).template_collection_id, otherCollection.id)
    await pages.renamePageTemplateCollection(collection.id, { name: 'Bộ sưu tập đã đổi' })
    assert.equal((await pages.getPageTemplateCollections()).find(row => row.id === collection.id).name, 'Bộ sưu tập đã đổi')
    const cloned = await pages.getAdminPageBySlug(clone.slug)
    assert.deepEqual(cloned.blocks[0].content, block.content)
    await pages.updateBlock(cloned.blocks[0].id, { content: { title: { vi: 'Bản sao chỉnh sửa' } } })
    assert.deepEqual((await pages.getAdminPageBySlug(template.slug)).blocks[0].content, block.content)
    const used = await pages.usePageTemplate(template.id, { slug: `su-dung-${randomUUID()}`, title: { vi: 'Trang mới', en: 'New page' } })
    ids.push(used.id)
    assert.equal(used.is_template, false)
    assert.equal(used.is_published, false)
    assert.deepEqual(used.sub_nav, source.sub_nav)
    assert.deepEqual((await pages.getAdminPageBySlug(used.slug)).blocks[0].content, block.content)
    await assert.rejects(() => pages.usePageTemplate(template.id, { slug: used.slug }))
    const preset = await pages.createPageTemplate({ name: 'Mẫu dựng sẵn', blocks: [{ block_type: 'split', content: { title: { vi: 'Giới thiệu' } }, label: 'Giới thiệu' }] })
    ids.push(preset.id)
    assert.equal((await pages.getAdminPageBySlug(preset.slug)).blocks.length, 1)
    await pages.renamePageTemplate(preset.id, 'Tên mới')
    assert.equal((await pages.getPageTemplates()).find(row => row.id === preset.id).template_name, 'Tên mới')
    await pages.deletePageTemplate(preset.id)
    assert.equal((await pages.getAdminPageBySlug(preset.slug)).page, null)
    await pages.deletePageTemplateCollection(collection.id)
    await pages.deletePageTemplateCollection(otherCollection.id)
    assert.equal((await pages.getPageTemplates()).find(row => row.id === template.id).template_collection_id, null)
    assert.equal((await pages.getPageTemplates()).find(row => row.id === clone.id).template_collection_id, null)
    console.log('Page template integration checks passed')
  } finally {
    await db.pageTemplateCollection.deleteMany({ where: { id: { in: collectionIds } } })
    await db.page.deleteMany({ where: { id: { in: ids } } })
    await db.$disconnect()
  }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
